import { createServer } from "node:http";
import { existsSync, readFileSync, statSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { validateXsd } from "./xsd.ts";
import { validateRules } from "./rules.ts";
import { createLimiter } from "./auth.ts";
import { createAdmin } from "./admin.ts";
import { monthOf, openDb, type Db } from "./db.ts";

const MAX_BYTES = 2 << 20; // NF-e XML limit is far below this

// Anonymous try-out used by the web page, limited per IP so the API key never has to be shipped to the browser.
// Counters are the browser-independent kind: clearing cookies or local storage does not reset them.
const ANON = { perMinute: 5, perMonth: 300 };
// Rejected XMLs are free, so the calls that come back invalid are capped separately to keep the free iterations from becoming free compute.
const FAIR_USE_FACTOR = 10; // total calls (valid or not) per month <= quota x this

const PUBLIC = fileURLToPath(new URL("../public/", import.meta.url));
const SITE = fileURLToPath(new URL("../site/", import.meta.url)); // generated by scripts/build-site.ts
const ASSETS: Record<string, [file: string, type: string]> = {
  "/app.js": ["app.js", "text/javascript; charset=utf-8"],
  "/app.css": ["app.css", "text/css; charset=utf-8"],
};
const TYPES: Record<string, string> = { html: "text/html; charset=utf-8", xml: "application/xml; charset=utf-8", txt: "text/plain; charset=utf-8" };

export function makeServer(store: Db, adminPassword?: string, siteDir = SITE) {
  const limiter = createLimiter();
  const admin = createAdmin(store, adminPassword);
  return createServer(async (req, res) => {
    const reply = (status: number, body: unknown, headers: Record<string, string | number> = {}) => {
      res.writeHead(status, { "content-type": "application/json", ...headers });
      res.end(JSON.stringify(body));
    };
    if (req.url?.startsWith("/admin")) return admin(req, res);

    const route = `${req.method} ${req.url}`;
    if (req.method === "GET" && !req.url?.startsWith("/v1/")) {
      const path = (req.url ?? "/").split("?")[0];
      const asset = ASSETS[path];
      // Only characters that can appear in generated paths; this also rules out "..".
      const ok = /^[a-z0-9/_.-]*$/i.test(path) && !path.includes("..");
      const rel = path.endsWith("/") ? path + "index.html" : path;
      const file = asset ? PUBLIC + asset[0] : ok ? siteDir + rel.slice(1) : "";
      const headers = {
        // Everything is same-origin and the pages make no third-party requests.
        "content-security-policy": "default-src 'self'; frame-ancestors 'none'",
        "x-content-type-options": "nosniff",
      };
      if (file && existsSync(file) && statSync(file).isFile()) {
        res.writeHead(200, { ...headers, "content-type": asset?.[1] ?? TYPES[file.split(".").pop()!] ?? "application/octet-stream", "cache-control": `public, max-age=${asset ? 3600 : 300}` });
        return res.end(readFileSync(file));
      }
      // /docs/api -> /docs/api/ so each page has a single address.
      if (ok && !path.endsWith("/") && existsSync(`${siteDir}${path.slice(1)}/index.html`)) { res.writeHead(301, { location: path + "/" }); return res.end(); }
      res.writeHead(404, { ...headers, "content-type": TYPES.html });
      return res.end(`<!doctype html><meta charset="utf-8"><meta name="robots" content="noindex"><title>Página não encontrada</title><link rel="stylesheet" href="/app.css"><main><h1>Página não encontrada</h1><p><a href="/">Voltar ao validador</a></p></main>`);
    }
    if (!["POST /v1/validate", "POST /v1/try", "GET /v1/usage"].includes(route)) return reply(404, { error: "not_found" });

    let denied: { error: string; retryAfter: number } | undefined;
    let billed: { clientId: number; keyId: number } | undefined;
    if (route === "POST /v1/try") {
      // behind a proxy the socket address is the proxy's; set TRUST_PROXY=1 only if it overwrites X-Forwarded-For.
      const fwd = process.env.TRUST_PROXY ? String(req.headers["x-forwarded-for"] ?? "").split(",")[0].trim() : "";
      denied = limiter.take(`ip:${fwd || req.socket.remoteAddress}`, ANON.perMinute, ANON.perMonth);
    } else {
      const bearer = /^Bearer (.+)$/.exec(req.headers.authorization ?? "")?.[1];
      const found = store.findKey(bearer ?? (req.headers["x-api-key"] as string | undefined));
      if (!found) return reply(401, { error: "unauthorized" });
      if (found.revoked) return reply(403, { error: "access_revoked" });
      const c = found.client;
      const used = store.usedIn(c.id, monthOf(Date.now()));
      if (route === "GET /v1/usage") return reply(200, { client: c.name, used, perMonth: c.perMonth });
      denied = limiter.take(`c${c.id}`, c.perMinute, c.perMonth, used);
      if (!denied && store.usedIn(c.id, monthOf(Date.now()), true) >= c.perMonth * FAIR_USE_FACTOR)
        denied = { error: "fair_use_exceeded", retryAfter: 3600 };
      billed = { clientId: c.id, keyId: found.keyId };
    }
    if (denied) return reply(429, { error: denied.error }, { "retry-after": denied.retryAfter });

    let xml = "";
    req.setEncoding("utf8");
    for await (const chunk of req) {
      xml += chunk;
      if (xml.length > MAX_BYTES) return reply(413, { error: "payload_too_large" });
    }
    try {
      // Business rules assume a structurally valid document, so they only run once the XSD passes.
      let issues = await validateXsd(xml);
      if (issues.length === 0) issues = validateRules(xml);
      if (billed) { // only API calls are billable; the usage row is the invoice line
        store.logUsage(billed.clientId, issues.length === 0);
        store.touchKey(billed.keyId);
      }
      else store.logEvent(issues.length === 0 ? "try_valid" : "try_invalid");
      reply(200, { valid: issues.length === 0, issues });
    } catch {
      reply(500, { error: "validator_failed" });
    }
  });
}

if (import.meta.main) {
  const port = Number(process.env.PORT ?? 3000);
  makeServer(openDb(process.env.DB_FILE ?? "nfe-preflight.db"), process.env.ADMIN_PASSWORD).listen(port);
  if (!process.env.ADMIN_PASSWORD) console.warn("ADMIN_PASSWORD not set: /admin is disabled");
}
